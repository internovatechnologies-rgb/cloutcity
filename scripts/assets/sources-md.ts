/**
 * Renders data/assets/SOURCES.md from the catalog, the download lock and the Blender lock, so the
 * record of every pack (version, URL or commit, sha256, licence evidence) and every shipped model
 * can never drift from what the build actually used.
 */
import type { BlenderLock } from '../blender/build.ts'
import type { Catalog, Source, SourcesLock } from './schema.ts'

const LICENCE_TEXT: Readonly<Record<string, string>> = {
  'CC0-1.0':
    'CC0 1.0 Universal (public domain dedication) <https://creativecommons.org/publicdomain/zero/1.0/>',
  MIT: 'MIT License <https://opensource.org/license/mit>',
  'project-original':
    'Project-original: modelled for Clout City: NYC by our own committed Blender scripts (DEC-25); no third-party licence',
}

function downloadLine(source: Source): string {
  const { download } = source
  if (download.kind === 'zip')
    return `- Download: <${download.url}> (models under \`${download.root}/\`)`
  if (download.kind === 'github-raw') {
    return `- Download: raw files of <https://github.com/${download.repo}> at commit \`${download.commit}\` (models under \`${download.root}/\`)`
  }
  return `- Built by \`npm run blender:build\` into \`${download.root}/\` (Blender pinned in scripts/blender/lock.json)`
}

function sourceSection(
  catalog: Catalog,
  source: Source,
  lock: SourcesLock,
  blender: BlenderLock,
): string[] {
  const models = catalog.models.filter((model) => model.source === source.id)
  const lines = [
    `### ${source.title} ${source.version}`,
    '',
    `- Id: \`${source.id}\``,
    `- Author: ${source.author}`,
    `- Page: <${source.homepage}>`,
    `- Licence: ${LICENCE_TEXT[source.licence] ?? source.licence}`,
    `- Licence evidence: \`${source.licenceEvidence.entry}\` contains ${source.licenceEvidence.mustContain.map((p) => `"${p}"`).join(' and ')}`,
    downloadLine(source),
    `- Colour grade (OKLCH): lightness × ${source.grade.lightness}, chroma × ${source.grade.chroma}`,
  ]
  const locked = lock.sources.find((entry) => entry.id === source.id)
  if (locked !== undefined) {
    lines.push(
      `- Retrieved: ${locked.retrieved}`,
      '',
      '| File | Bytes | sha256 |',
      '|---|---:|---|',
    )
    for (const file of locked.files)
      lines.push(`| \`${file.path}\` | ${file.bytes} | \`${file.sha256}\` |`)
  } else if (source.download.kind === 'local') {
    const outputs = blender.models.filter((model) =>
      models.some((m) => m.entries.some((e) => e.path === `${model.id}.glb`)),
    )
    if (outputs.length > 0) {
      lines.push('', '| Output | Bytes | sha256 | Script |', '|---|---:|---|---|')
      for (const output of outputs) {
        lines.push(
          `| \`${output.id}.glb\` | ${output.bytes} | \`${output.sha256}\` | \`${output.script}\` |`,
        )
      }
    }
  }
  lines.push(
    '',
    models.length === 0
      ? 'Models: none yet.'
      : `Models: ${models.map((model) => `\`${model.id}\``).join(', ')}.`,
    '',
  )
  return lines
}

export function renderSourcesMd(catalog: Catalog, lock: SourcesLock, blender: BlenderLock): string {
  const lines = [
    '# 3D model sources',
    '',
    'Generated by `npm run assets:build` from `data/assets/catalog.json`, `scripts/assets/sources.lock.json`',
    'and `scripts/blender/lock.json`. Do not edit by hand.',
    '',
    'Every model is either from a free hand-made low-poly pack with a CC0 (or MIT) licence (DEC-24),',
    'pinned by URL or commit and sha256, or modelled by our own Blender scripts (DEC-25). The build',
    'refuses any other licence and checks each pack’s licence file on every run.',
    '',
    '## What the build changes',
    '',
    '- Bakes each face’s material colour (base colour × texture atlas swatch) into vertex colours, then',
    '  drops every texture, image, UV and tangent. No pack artwork ships as an image.',
    '- Grades colours per pack in OKLCH and snaps them to the real-world model palette',
    '  (`data/config/theme.json` → `models`, DEC-26) within a CIEDE2000 tolerance.',
    '- Merges each static model into one mesh, scales it to real-world size and re-centres it.',
    '- Simplifies per quality tier (meshoptimizer), quantizes and compresses (EXT_meshopt_compression).',
    '- Avatar parts keep the shared Kenney rig; the rig keeps only the clips listed in the catalog.',
    '',
    '## Attribution',
    '',
    'Not required by CC0; credited on /credits as thanks: Kenney (www.kenney.nl) and Kay Lousberg',
    '(www.kaylousberg.com).',
    '',
    '## Packs',
    '',
  ]
  for (const source of catalog.sources) lines.push(...sourceSection(catalog, source, lock, blender))
  lines.push('## Models', '', '| Model | Pack | Files | Category |', '|---|---|---|---|')
  for (const model of catalog.models) {
    lines.push(
      `| \`${model.id}\` | \`${model.source}\` | ${model.entries.map((entry) => `\`${entry.path}\``).join(', ')} | ${model.category} |`,
    )
  }
  lines.push('', '## Left out', '', '| Item | Why |', '|---|---|')
  for (const excluded of catalog.excluded) lines.push(`| ${excluded.item} | ${excluded.reason} |`)
  lines.push('')
  return lines.join('\n')
}
